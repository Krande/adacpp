"""Regenerate src/render/overlay_fonts.h: DejaVu Sans, Sans Bold and Sans Mono, subset to the characters the
overlay (orientation gizmo, colour legend) draws, as C arrays -- so the renderer needs neither font files
nor FreeType at run time. Needs fontTools and the DejaVu TTFs (Debian/Ubuntu: fonts-dejavu-core).

    python tools/gen_overlay_fonts.py [/usr/share/fonts/truetype/dejavu]
"""

import io
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

# Printable ASCII plus what legends write: em dash, ellipsis, Delta, middle dot, degree, micro, plus-minus,
# times, minus, superscripts 2/3.
CHARS = [*range(0x20, 0x7F), 0x2014, 0x2026, 0x0394, 0x00B7, 0x00B0, 0x00B5, 0x00B1, 0x00D7, 0x2212, 0x00B2, 0x00B3]
FONTS = {"kFontSans": "DejaVuSans.ttf", "kFontSansBold": "DejaVuSans-Bold.ttf", "kFontMono": "DejaVuSansMono.ttf"}


def subset_font(path: Path) -> bytes:
    font = TTFont(path)
    options = subset.Options()
    options.layout_features = []
    options.name_IDs = ["*"]  # keep the names: the licence notice lives there
    options.hinting = False
    sub = subset.Subsetter(options)
    sub.populate(unicodes=CHARS)
    sub.subset(font)
    out = io.BytesIO()
    font.save(out)
    return out.getvalue()


def main() -> None:
    src = Path(sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu")
    root = Path(__file__).resolve().parents[1]
    lines = [
        "// Generated by tools/gen_overlay_fonts.py -- do not edit. DejaVu fonts (Bitstream Vera licence,",
        "// third_party/dejavu/LICENSE), subset to the characters the overlay draws.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "",
        "namespace adacpp::render {",
        "",
    ]
    for name, file in FONTS.items():
        data = subset_font(src / file)
        lines.append(f"// {file}, {len(data)} bytes")
        lines.append(f"inline constexpr unsigned char {name}[] = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ", ".join(str(b) for b in data[i : i + 24]) + ",")
        lines.append("};")
        lines.append("")
    lines.append("} // namespace adacpp::render")
    (root / "src/render/overlay_fonts.h").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
