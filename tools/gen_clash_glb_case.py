"""Generate tests/fixtures/clash/glb_case.{glb,json} -- a real viewer GLB and the contacts in it.

The GLB is what the viewer loads for files/my_test.ifc: adacpp's native IFC -> GLB stream
(merge-by-colour, id_hierarchy + draw_ranges, EXT_meshopt_compression). The JSON is what
``adacpp.clash.find_glb_contacts`` reports on those bytes. The GLB is frozen here on purpose: the
tests hold the browser (wasm) and the worker (nanobind) to one answer on the SAME bytes, and a GLB
regenerated by a later converter would be different bytes, not a different answer.

    pixi run -e test python tools/gen_clash_glb_case.py tests/fixtures/clash
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import adacpp.cad
import adacpp.clash

ROOT = Path(__file__).resolve().parents[1]
SECURITY_MARGIN = 0.01
MIN_CONTACT_AREA = 1e-6
LINE_CONTACT_THICKNESS = 1e-3


def expected(glb: Path) -> dict:
    r = adacpp.clash.find_glb_contacts(
        glb,
        security_margin=SECURITY_MARGIN,
        min_contact_area=MIN_CONTACT_AREA,
        line_contact_thickness=LINE_CONTACT_THICKNESS,
    )
    contacts = []
    for q, (i, j) in enumerate(r["pairs"].tolist()):
        contacts.append(
            {
                "pair": [i, j],
                "near1": r["near1"][q].tolist(),
                "near2": r["near2"][q].tolist(),
                "normal": r["normal"][q].tolist(),
                "penetration_depth": float(r["penetration_depth"][q]),
                "contact_area": float(r["contact_area"][q]),
                "patches": [
                    {"normal": list(p["normal"]), "points1": p["points1"].tolist(), "points2": p["points2"].tolist()}
                    for p in r["patches"][q]
                ],
            }
        )
    return {
        "schema": "adacpp.clash.glb_case/1",
        "glb": glb.name,
        "source": "files/my_test.ifc via adacpp.cad.stream_ifc_to_glb (meshopt)",
        "security_margin": SECURITY_MARGIN,
        "min_contact_area": MIN_CONTACT_AREA,
        "line_contact_thickness": LINE_CONTACT_THICKNESS,
        "members": [list(m) for m in r["members"]],
        "contacts": contacts,
        "below_min_area": int(r["below_min_area"]),
        "candidate_pairs": int(r["candidate_pairs"]),
    }


def main(out_dir: str) -> None:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    glb = out / "glb_case.glb"
    if adacpp.cad.stream_ifc_to_glb(str(ROOT / "files" / "my_test.ifc"), str(glb), meshopt=True) <= 0:
        raise SystemExit("stream_ifc_to_glb wrote no products")
    doc = expected(glb)
    (out / "glb_case.json").write_text(json.dumps(doc, indent=1) + "\n", encoding="utf-8")
    print(f"wrote {glb} ({glb.stat().st_size} bytes): {len(doc['members'])} members, {len(doc['contacts'])} contacts")


if __name__ == "__main__":
    main(sys.argv[1])
